/** Reports what the most recently attached client can do, for the dashboard card. */
let attachedClientSampling: boolean | null = null;

function zodShape(tool: ToolDefinition): Record<string, unknown> {
  return (tool.input as unknown as { shape?: Record<string, unknown> }).shape ?? {};
}

/**
 * Builds a fresh MCP server with every tool registered. A server is built per session — over
 * stdio once, over HTTP per connection — because sampling is asked back over the transport of
 * the session that asked, so the context has to belong to exactly one client.
 */
function buildMcpServer(origin: string): { server: McpServer; ctx: ToolContext } {
  const server = new McpServer(
    { name: "winsecure-mcp", version: VERSION },
    {
      instructions:
        "Windows software inventory against the CVE sources. scan_inventory reads the machine, check_cves fills the " +
        "to-do list, list_todos shows it, assess_todo rates the patch effort. Nothing here changes the system: the " +
        "server only ever writes its own JSON files.",
    },
  );

  // Sampling is decided per session, so the flag lives next to the server it is asked over.
  let samplingActive = false;

  const context: ToolContext = {
    config,
    store,
    http,
    clientSampling: () => samplingActive,
    async sample(prompt: string) {
      if (!samplingActive) return null;
      try {
        const res = await server.server.createMessage({
          messages: [{ role: "user", content: { type: "text", text: prompt } }],
          maxTokens: 512,
        });
        if (res.content.type !== "text") return null;
        return { text: res.content.text };
      } catch (cause) {
        process.stderr.write(`  sampling failed: ${String(cause instanceof Error ? cause.message : cause)}\n`);
        return null;
      }
    },
  };

  for (const tool of ALL_TOOLS) {
    server.registerTool(
      tool.name,
      { title: tool.title, description: tool.description, inputSchema: zodShape(tool) as never },
      ((args: Record<string, unknown>) => invoke(tool, args ?? {}, context, origin)) as never,
    );
  }

  // A read-only window onto the store file, so an agent can inspect the inventory/to-do JSON without
  // invoking a tool. It reads the file fresh each time, so it never disagrees with a prior write.
  server.registerResource(
    "winsecure.json",
    "winsecure://store.json",
    { title: "winsecure store", description: "The server's own JSON store: inventory and to-do list.", mimeType: "application/json" },
    async (uri) => ({
      contents: [
        { uri: uri.href, mimeType: "application/json", text: JSON.stringify(store.load(), null, 2) },
      ],
    }),
  );

  // The client capabilities are only known after the handshake, so sampling is decided here rather
  // than at construction time.
  server.server.oninitialized = () => {
    const caps = server.server.getClientCapabilities();
    samplingActive = Boolean(caps?.sampling);
    attachedClientSampling = samplingActive;
    const client = server.server.getClientVersion();
    process.stderr.write(
      `  client connected (${origin}): ${client?.name ?? "unknown"} ${client?.version ?? ""}` +
        ` — sampling ${String(Boolean(caps?.sampling))}, elicitation ${String(Boolean(caps?.elicitation))}\n`,
    );
  };

  return { server, ctx: context };
}

// ---------------------------------------------------------------------------
// HTTP control plane (web interface + MCP over Streamable HTTP)
// ---------------------------------------------------------------------------

/**
 * A client that declared sampling can answer `sampling/createMessage`. A dashboard assessment
 * runs through a context without a session, so it always gets the evidence package instead.
 */
interface McpHttpSession {
  server: McpServer;
  transport: StreamableHTTPServerTransport;
  lastSeen: number;
}

const httpSessions = new Map<string, McpHttpSession>();

/** A session that no client touched for half an hour is assumed gone. */
const SESSION_IDLE_MS = 30 * 60 * 1000;

/**
 * MCP over Streamable HTTP, with real sessions. Stateless-per-request would answer every
 * `tools/call` with a server that never saw the client's `initialize`, so the client capabilities
 * — and with them sampling — would always look absent.
 */
async function handleMcpHttp(req: IncomingMessage, res: ServerResponse): Promise<void> {
  for (const [id, session] of httpSessions) {
    if (Date.now() - session.lastSeen > SESSION_IDLE_MS) {
      httpSessions.delete(id);
      await session.transport.close().catch(() => undefined);
      await session.server.close().catch(() => undefined);
    }
  }

  const wanted = req.headers["mcp-session-id"];
  const sessionId = Array.isArray(wanted) ? wanted[0] : wanted;

  let session = sessionId ? httpSessions.get(sessionId) : undefined;
  if (sessionId && !session) {
    res.writeHead(404, { "content-type": "application/json" });
    res.end(JSON.stringify({ error: "Unknown MCP session" }));
    return;
  }

  if (!session) {
    const built = buildMcpServer("http");
    const transport = new StreamableHTTPServerTransport({ sessionIdGenerator: () => randomUUID() });
    // The session must outlive the request that created it, so nothing is closed on `res.close`.
    transport.onclose = () => {
      const id = transport.sessionId;
      if (id && httpSessions.has(id)) {
        httpSessions.delete(id);
        void built.server.close();
      }
    };
    await built.server.connect(transport);
    await transport.handleRequest(req, res);
    if (transport.sessionId) {
      httpSessions.set(transport.sessionId, { server: built.server, transport, lastSeen: Date.now() });
    } else {
      // A failed handshake: nothing to keep.
      await transport.close();
      await built.server.close();
    }
    return;
  }

  session.lastSeen = Date.now();
  if (req.method === "DELETE") {
    await session.transport.handleRequest(req, res);
    httpSessions.delete(sessionId ?? "");
    await session.server.close();
    return;
  }
  await session.transport.handleRequest(req, res);
}

async function handleApi(req: IncomingMessage, res: ServerResponse, url: URL): Promise<void> {
  const send = (status: number, body: unknown): void => {
    res.writeHead(status, { "content-type": "application/json" });
    res.end(JSON.stringify(body));
  };

  if (url.pathname === "/api/state") {
    return send(200, computeState({
      version: VERSION,
      store: store.load(),
      storeExists: storeExists(store),
      dataDir: config.settings.dataDir,
      storePath: store.path,
      tools: ALL_TOOLS,
      activity: activity.recent(20),
      clientSampling: attachedClientSampling,
      nvdKey: { present: resolveNvdKey(config).key !== null, source: resolveNvdKey(config).source },
    }));
  }

  // The dashboard's NVD key section. The key itself never travels to the browser — the answer
  // says whether one is set and where it came from, nothing more.
  if (url.pathname === "/api/nvd_key") {
    if (req.method === "POST") {
      const chunks: Buffer[] = [];
      for await (const chunk of req) chunks.push(chunk as Buffer);
      const raw = Buffer.concat(chunks).toString("utf8");
      const body = (raw ? JSON.parse(raw) : {}) as { key?: unknown };
      const candidate = String(body.key ?? "").trim();
      if (candidate === "") {
        config.settings.nvdApiKey = null;
        config.save();
        return send(200, { ok: true, key_present: false, mode: "keyless-osv+cached" });
      }
      const check = await validateNvdKey(candidate, config.settings.httpTimeoutMs);
      if (!check.valid) {
        // The console contract: a failed validation says the same line the startup hint says.
        process.stderr.write("  no valid NVD API key — check dashboard\n");
        return send(400, { ok: false, error: check.error ?? "invalid key" });
      }
      config.settings.nvdApiKey = candidate;
      config.save();
      return send(200, { ok: true, key_present: true, source: "config", mode: "nvd-keyed" });
    }
    const state = resolveNvdKey(config);
    return send(200, {
      key_present: state.key !== null,
      source: state.source,
      mode: state.key !== null ? "nvd-keyed" : "keyless-osv+cached",
      last_validation: nvdKeyValidation,
      request_url: "https://nvd.nist.gov/developers/request-an-api-key",
    });
  }

  if (url.pathname === "/api/run" && req.method === "POST") {
    const chunks: Buffer[] = [];
    for await (const chunk of req) chunks.push(chunk as Buffer);
    const raw = Buffer.concat(chunks).toString("utf8");
    const body = (raw ? JSON.parse(raw) : {}) as { tool?: unknown; args?: Record<string, unknown> };
    const tool = TOOLS_BY_NAME.get(String(body.tool ?? ""));
    if (!tool) return send(404, { error: `Unknown tool "${String(body.tool)}"` });
    // A dashboard scan/check runs with the same defaults as an agent call, through the same
    // handler and the same store, so both views stay consistent.
    const result = await invoke(tool, body.args ?? {}, webCtx, "web");
    return send(200, {
      ok: result.isError !== true,
      output: result.content.map((c) => ("text" in c ? c.text : "")).join("\n"),
    });
  }

  return send(404, { error: `No API route for ${url.pathname}` });
}

// The dashboard endpoints answer from a context without a session, so an assessment triggered in
// the browser gets the evidence package rather than a sampling request.
const webCtx: ToolContext = { config, store, http, clientSampling: () => false, sample: async () => null };

/** The outcome of the background key probe started at launch, for the dashboard badge. */
let nvdKeyValidation: { valid: boolean; error?: string; at: string } | null = null;

function serveHtml(res: ServerResponse): void {
  res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
  res.end(readFileSync(fileURLToPath(new URL("./webui.html", import.meta.url)), "utf8"));
}

async function main(): Promise<void> {
  if (ARGS.get("help") === true) {
    process.stdout.write(HELP);
    process.exit(0);
  }

  const webDisabled = ARGS.get("no-web") === true || process.env.WSMD_NO_WEB === "1";
  const port = Number(ARGS.get("port") ?? process.env.WSMD_PORT ?? 8788);
  // Bound to every interface by default, because the client usually sits in WSL and reaches this
  // process through the virtual network adapter; --host / WSMD_HOST narrows it down.
  const hostArg = ARGS.get("host");
  const bindHost =
    typeof hostArg === "string" && hostArg !== ""
      ? hostArg
      : (process.env.WSMD_HOST ?? "0.0.0.0");

  const httpServer = createServer(async (req, res) => {
    const url = new URL(req.url ?? "/", `http://${req.headers.host ?? "localhost"}`);
    // Tolerate a trailing slash: some clients (and url: entries typed by hand) request "/mcp/".
    const path = url.pathname.length > 1 ? url.pathname.replace(/\/+$/, "") : url.pathname;
    try {
      if (path.startsWith("/api/")) {
        await handleApi(req, res, url);
        return;
      }
      if (path === "/mcp") {
        await handleMcpHttp(req, res);
        return;
      }
      if (req.method === "GET") {
        serveHtml(res);
        return;
      }
      res.writeHead(404, { "content-type": "text/plain" }).end("not found");
    } catch (cause) {
      res.writeHead(500, { "content-type": "text/plain" });
      res.end(String(cause instanceof Error ? cause.message : cause));
    }
  });

  process.stderr.write(`\n${BANNER}`);
  process.stderr.write(`  version         v${VERSION}\n`);
  process.stderr.write(`  data directory  ${config.settings.dataDir}\n`);
  process.stderr.write(`  store file      ${store.path}\n`);

  if (webDisabled) {
    process.stderr.write("  web interface disabled (--no-web)\n");
  } else {
    await new Promise<void>((resolve, reject) => {
      httpServer.once("error", reject);
      httpServer.listen(port, bindHost, () => resolve());
    });
    process.stderr.write(`  web interface   http://${bindHost}:${String(port)}\n`);
  }
  process.stderr.write("  MCP transport   stdio — this terminal stays attached to the agent\n");

  // The key line is the operator's first hint at which lookup mode a check_cves will run in.
  const keyState = resolveNvdKey(config);
  if (keyState.key === null) {
    process.stderr.write("  no valid NVD API key — check dashboard\n");
    process.stderr.write(
      "  running keyless, not optimal — rate limits apply, results may be less complete\n" +
        "  https://github.com/prinzalx/winsecure-mcp/blob/main/docs/nvd-key-vs-keyless.md\n",
    );
  } else {
    process.stderr.write(`  NVD API key     set (from ${keyState.source === "env" ? "NVD_API_KEY" : "config"}) — mode nvd-keyed\n`);
    // A stored key is re-validated in the background, so a key that stopped working (typo, NVD
    // revocation) prints the same honest line again instead of silently querying into 401s.
    void validateNvdKey(keyState.key, config.settings.httpTimeoutMs).then((check) => {
      nvdKeyValidation = { ...check, at: new Date().toISOString() };
      if (!check.valid) process.stderr.write("  no valid NVD API key — check dashboard\n");
    });
  }
  process.stderr.write("\n");

  // stdio is the MCP transport; the web interface keeps running in the same process.
  const { server } = buildMcpServer("stdio");

  // When the MCP client closes stdin, the web interface must not keep the process alive.
  const shutdown = () => {
    httpServer.close();
    void server.close();
    process.exit(0);
  };
  process.stdin.on("end", shutdown);
  process.stdin.on("close", shutdown);
  process.on("SIGINT", shutdown);
  process.on("SIGTERM", shutdown);

  const transport = new StdioServerTransport();
  await server.connect(transport);
}

/**
 * Runs a tool with input validation and error capture.
 *
 * A handler that throws is turned into a failed result rather than an MCP protocol error, so a
 * client sees the message and the server keeps its session.
 */
async function invoke(
  tool: ToolDefinition,
  args: Record<string, unknown>,
  ctx: ToolContext,
  origin = "web",
) {
  const parsed = tool.input.safeParse(args ?? {});
  if (!parsed.success) {
    const message = parsed.error.issues.map((i) => `${i.path.join(".") || "input"}: ${i.message}`).join("; ");
    return fail(`Invalid input for ${tool.name} — ${message}`);
  }
  const started = Date.now();
  try {
    const result = await tool.handler(parsed.data as Record<string, unknown>, ctx);
    const ms = Date.now() - started;
    process.stderr.write(`  ${result.isError ? "err " : "ok  "} ${tool.name} (${origin}) ${String(ms)} ms\n`);
    activity.add({
      at: new Date().toISOString(),
      tool: tool.name,
      ok: result.isError !== true,
      duration_ms: ms,
      origin,
      summary: result.content.map((c) => ("text" in c ? c.text : "")).join(" ").slice(0, 300),
    });
    return result;
  } catch (cause) {
    const message = cause instanceof Error ? cause.message : String(cause);
    process.stderr.write(`  err  ${tool.name} threw: ${message}\n`);
    activity.add({ at: new Date().toISOString(), tool: tool.name, ok: false, duration_ms: Date.now() - started, origin, summary: message });
    return fail(`${tool.name} threw: ${message}`);
  }
}

main().catch((cause: unknown) => {
  process.stderr.write(`fatal: ${String(cause instanceof Error ? cause.message : cause)}\n`);
  process.exit(1);
});

